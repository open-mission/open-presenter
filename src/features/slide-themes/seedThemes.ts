function textElement(
  id: string,
  text: string,
  css: Record<string, string>,
  name?: string,
): ThemeElement {
  return {
    id,
    name,
    type: "TEXT",
    x: 0,
    y: 0,
    visible: true,
    locked: false,
    css,
    text,
  };
}

function barElement(
  id: string,
  fill: string,
  css: Record<string, string>,
  name?: string,
): ThemeElement {
  return {
    id,
    name,
    type: "RECTANGLE",
    x: 0,
    y: 0,
    visible: true,
    locked: false,
    css,
    fill,
  };
}

function page(
  id: string,
  context: ThemeContext,
  background: string,
  elements: ThemeElement[],
): ThemePage {
  return {
    id,
    context,
    css: { background },
    elements,
  };
}

